// 本文件【不碰 Java】，这里只是把日志里的读数与此对齐，避免日志报一个假的 cap）
var EDM_CAP = '2/144/0/32'
// 物品输出上限 / 流体输出上限（同一处真源的第 2、第 4 个数；越界自查拿它们比，不写死数字）
var EDM_CAP_ITEM_OUT = 144
var EDM_CAP_FLUID_OUT = 32

ServerEvents.recipes(function (event) {
    var gtr = event.recipes.gtceu
    var ok = 0
    var bad = 0
    var errList = ''
    var usedMax = [0, 0, 0, 0]
    var overList = ''
    var overFluid = ''
    for (var i = 0; i < edmRecipes.length; i++) {
        var R = edmRecipes[i]
        try {
            var b = gtr['primordial_deep_space_extraction']('shanhai:primordial_deep_space/elevator_mk' + R.mk)
                .notConsumable(R.module)
                .EUt(R.eu)
                .duration(200)
            var j
            for (j = 0; j < R.ores.length; j++) b.chancedOutput(R.ores[j][0], R.ores[j][1], 0)
            for (j = 0; j < R.fluids.length; j++) b.outputFluids(R.fluids[j])
            var used = [1, R.ores.length, 0, R.fluids.length]
            for (j = 0; j < 4; j++) if (used[j] > usedMax[j]) usedMax[j] = used[j]
            // 越界自查（物品）：超过类型上限时响亮地记一笔（不抛异常，配方照旧注册）
            if (R.ores.length > EDM_CAP_ITEM_OUT) overList = overList + ' mk' + R.mk + '=' + R.ores.length + '/' + EDM_CAP_ITEM_OUT
            // 越界自查（流体）：【故意只记 info 不记 error】—— 流体上限的放宽正随界面改版一起做，
            // 载入时的红字是用户明确不喜欢的东西；读数留在日志里，上限抬上去之后自然不再出现。
            if (R.fluids.length > EDM_CAP_FLUID_OUT) overFluid = overFluid + ' mk' + R.mk + '=' + R.fluids.length + '/' + EDM_CAP_FLUID_OUT
            ok = ok + 1
            console.info('[SHANHAI-EDM] MK' + R.mk + '(' + R.zh + ') ok id=shanhai:primordial_deep_space/elevator_mk' + R.mk
                + ' catalyst=' + R.module
                + ' ores=' + R.ores.length
                + ' fluids=' + R.fluids.length
                + ' eu=' + R.eu
                + ' used=' + used.join('/') + ' cap=' + EDM_CAP)
        } catch (e) {
            bad = bad + 1
            errList = errList + ' | mk' + R.mk + '=>' + e
        }
    }
    console.info('[SHANHAI-EDM] 原初深空汲取·太空电梯采集+钻井 register ok=' + ok + ' failed=' + bad
        + ' type=primordial_deep_space_extraction(原初深空汲取)'
        + ' machine=shanhai:primordial_deep_space_extraction_core'
        + ' 峰值占用 used=' + usedMax.join('/') + ' cap=' + EDM_CAP)
    if (overFluid.length > 0) console.info('[SHANHAI-EDM] 流体输出超过当前类型上限 ' + EDM_CAP_FLUID_OUT + '：' + overFluid
        + '（已知待放宽项：与界面改版一起把 .rtui 的 fluid_out 与 Java 第 4 个数抬到 ≥ ' + usedMax[3] + '；'
        + ' 配方照旧注册，超出的项在 JEI 里没有流体槽可填。这里【故意用 info 不用 error】）')
    if (overList.length > 0) console.error('[SHANHAI-EDM] 物品输出超出类型上限 ' + EDM_CAP_ITEM_OUT + '：' + overList
        + '（配方照旧注册；超出的项在 JEI 里没有槽可填 ⇒ 需放宽 setMaxIOSize + .rtui）')
    if (bad > 0) console.error('[SHANHAI-EDM] FAILED:' + errList)
})
